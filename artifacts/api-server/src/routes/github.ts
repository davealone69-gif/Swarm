import { Router, type IRouter } from "express";
import { ReplitConnectors } from "@replit/connectors-sdk";

const router: IRouter = Router();
const connectors = new ReplitConnectors();

interface ProjectFile {
  path: string;
  content: string;
}

function safeRepoName(value: unknown): string {
  const name = String(value ?? "swarm-generated-app")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90);
  return name || "swarm-generated-app";
}

type GithubRequest = {
  method?: string;
  headers?: Record<string, string>;
  body?: unknown;
};

async function github(path: string, init?: GithubRequest): Promise<any> {
  const response = await connectors.proxy("github", path, init);
  const body: any = await response.json().catch(() => ({}));
  if (!response.ok) {
    const message = body?.message ?? `GitHub request failed (${response.status})`;
    throw new Error(message);
  }
  return body;
}

router.post("/github/push-project", async (req, res) => {
  try {
    const repoName = safeRepoName(req.body?.repoName);
    const description = String(req.body?.description ?? "Generated by SWARM-BUILDER-ZERO").slice(0, 250);
    const files = Array.isArray(req.body?.files) ? req.body.files : [];

    if (files.length === 0 || files.length > 100) {
      return res.status(400).json({ error: "Send between 1 and 100 project files." });
    }

    const user = await github("/user");
    let repo: any;
    try {
      repo = await github(`/repos/${encodeURIComponent(user.login)}/${encodeURIComponent(repoName)}`);
    } catch {
      repo = await github("/user/repos", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name: repoName,
          description,
          private: true,
          auto_init: true,
        }),
      });
    }

    const branch = repo.default_branch || "main";
    let pushed = 0;
    for (const item of files as ProjectFile[]) {
      const path = String(item.path ?? "").replace(/^\/+/, "");
      if (!path || typeof item.content !== "string") continue;

      let sha: string | undefined;
      try {
        const existing = await github(
          `/repos/${encodeURIComponent(user.login)}/${encodeURIComponent(repoName)}/contents/${path}?ref=${encodeURIComponent(branch)}`,
        );
        if (!Array.isArray(existing)) sha = existing.sha;
      } catch {
        // New file: GitHub accepts a PUT without sha.
      }

      await github(`/repos/${encodeURIComponent(user.login)}/${encodeURIComponent(repoName)}/contents/${path}`, {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          message: `${sha ? "Update" : "Add"} ${path}`,
          content: Buffer.from(item.content, "utf8").toString("base64"),
          branch,
          ...(sha ? { sha } : {}),
        }),
      });
      pushed += 1;
    }

    return res.json({
      ok: true,
      pushed,
      repo: repo.full_name,
      url: repo.html_url,
      branch,
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : "GitHub push failed";
    return res.status(502).json({ error: message });
  }
});

export default router;